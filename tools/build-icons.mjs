#!/usr/bin/env node
// Regenerates web/js/icons.mjs from primer/octicons (MIT, https://github.com/primer/octicons).
//   node tools/build-icons.mjs
// Only the 16px glyphs the viewer uses are inlined, so the page needs no network or icon font.
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const run = promisify(execFile);
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'web', 'js', 'icons.mjs');
const BASE = 'https://raw.githubusercontent.com/primer/octicons/main/icons';

const NAMES = [
  'mark-github', 'copilot', 'code', 'device-desktop', 'apps', 'repo', 'shield-lock', 'megaphone', 'beaker', 'workflow',
  'rocket', 'sparkle', 'zap', 'alert', 'hourglass', 'calendar', 'clock', 'history', 'git-commit', 'git-branch',
  'search', 'x', 'check', 'info', 'sync', 'triangle-right', 'file', 'download', 'link-external', 'book', 'gear', 'people', 'tag',
  'chevron-left', 'chevron-right', 'chevron-down', 'chevron-up', 'arrow-right', 'arrow-left', 'screen-full', 'screen-normal',
  'graph', 'filter', 'terminal', 'package', 'light-bulb', 'globe', 'lock', 'key', 'law', 'comment-discussion',
  'sun', 'moon', 'location', 'versions',
];

async function fetchSvg(name) {
  try {
    const { stdout } = await run('curl.exe', ['-sSfL', '-m', '40', `${BASE}/${name}-16.svg`], { maxBuffer: 1 << 20 });
    return stdout;
  } catch { return null; }
}

function parse(svg) {
  const paths = [];
  for (const m of svg.matchAll(/<path\s+([^>]*?)\/?>/g)) {
    const attrs = {};
    for (const a of m[1].matchAll(/([\w-]+)="([^"]*)"/g)) if (['d', 'fill-rule', 'clip-rule'].includes(a[1])) attrs[a[1]] = a[2];
    if (attrs.d) paths.push(attrs);
  }
  const box = svg.match(/viewBox="0 0 (\d+) (\d+)"/);
  return paths.length ? { w: Number(box?.[1] || 16), h: Number(box?.[2] || 16), paths } : null;
}

const icons = {}; const missing = [];
const queue = [...NAMES];
await Promise.all(Array.from({ length: 6 }, async () => {
  while (queue.length) {
    const name = queue.shift();
    const def = parse((await fetchSvg(name)) || '');
    if (def) icons[name] = def; else missing.push(name);
  }
}));

const body = Object.keys(icons).sort().map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join('\n');
await writeFile(OUT, `// Generated by tools/build-icons.mjs from primer/octicons (MIT License, Copyright (c) GitHub, Inc.).
// The Invertocat ("mark-github") is a GitHub trademark: use it only as the brand guidelines allow (white, black, gray or green; no effects).
// Do not edit by hand.
export const ICONS = {
${body}
};
`);
console.log(`wrote ${Object.keys(icons).length} icons → ${path.relative(process.cwd(), OUT)}`);
if (missing.length) console.warn(`missing (not in octicons 16px set): ${missing.join(', ')}`);
